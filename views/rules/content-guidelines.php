<h1>Content Guidelines</h1>
<li>Only fanfictions are allowed. Fanfiction Online does not host non-fanfiction stories.</li>
<li>Plagarization is not allowed. Plagarization is intentionally copying another author’s story/part of story and presenting it as your own.</li>
<li>A story may not be posted more than once.</li>
<li>Sexual content involving characters under the age of 18 is not allowed.</li>
<li>Real-Person fiction, or stories about non-fictional characters is not allowed.</li>
<li>Stories must actually <strong>be</strong> stories. Collections, polls, author notes and chats cannot be posted as stories.</li>
<li>Stories must be tagged correctly.</li>
<li>If you want to add notes to your story, use the dedicated section for Author Notes. You may want to post an update if your notes are not specific to the story.</li>
<section>
    <h2>Ratings</h2>
        <li><strong>General Audiences:</strong> Stories suitable for all audiences.</li>
        <li><strong>Older Kids:</strong> Stories suitable for more mature children, 9 years & up.</li>
        <li><strong>Teen & Up:</strong> May not contain content for audiences below 13 years of age.</li>
        <li><strong>Mature:</strong> Stories may contain adult themes but not explicit descriptions of sexual or violent nature.</li>
        <li><strong>Explicit:</strong> May contain any content that falls within our content guidelines.</li>
</section>
<section>
    <h2>Removal</h2>
        <p>These guidelines are not exhaustive, and content we find not in line with our guidelines will be removed. Fanfiction Online has the right to remove any content or suspend/ban any account without prior notice.</p>
        <p>If you think there is content on Fanfiction Online that does not adhere to our guidelines, <a href="/contact">send us a message</a> with a reference to such content and we'll look in to it.</p>
</section>
