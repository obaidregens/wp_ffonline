<h3>Upload file to FFN</h3>
<ol >
<li>Go to Publish -> Doc Manager</li>
<li>Under <strong>Create New Document</strong>, enter a Label of your choice.</li>
<li>Select "File Upload" as the Method and the downloaded draft as the upload file.</li>
<li>Select "Story" as the Format.</li>
<li>Click on Submit Document.</li>
<li>Your Draft should get uploaded.</li>
</ol>